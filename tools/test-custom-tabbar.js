const assert = require('node:assert/strict');
let component, route = 'pages/study/study', request;
global.Component = value => { component = value; };
global.getCurrentPages = () => [{ route }];
global.wx = { switchTab(options) { request = options; }, showToast() {} };
require('../miniprogram/custom-tab-bar/index');
Object.assign(component, component.methods);
component.setData = patch => Object.assign(component.data, patch);
component.lifetimes.attached.call(component);
assert.equal(component.data.selected, 1);
component.switchTab({ currentTarget: { dataset: { index: 2 } } });
assert.equal(request.url, '/pages/ai/ai');
assert.equal(component.data.selected, 1);
request.fail(); request.complete();
assert.equal(component.data.selected, 1);
component.switchTab({ currentTarget: { dataset: { index: 2 } } });
route = 'pages/ai/ai'; request.success(); request.complete();
assert.equal(component.data.selected, 2);
route = 'pages/profile/profile'; component.pageLifetimes.show.call(component);
assert.equal(component.data.selected, 3);
console.log('PASS: direct route selection, switch target, failed navigation, selection sync');
